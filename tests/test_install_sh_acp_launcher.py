ATHANIEL_AGENT_BLOCK = re.compile(
    r'(rm -f "\$command_link_dir/athaniel-brain".*?'
    r'log_success "Installed athaniel-brain launcher[^\n]*\n)',
    re.S,
)


def _extract_athaniel_brain_shim_block() -> str:
    match = ATHANIEL_AGENT_BLOCK.search(INSTALL_SH.read_text(encoding="utf-8"))
    assert match, (
        "could not locate the athaniel-brain launcher block in scripts/install.sh — "
        "if it was renamed, update this test with it"
    )
    return match.group(1)


def _run_athaniel_brain_block(tmp_path: Path, use_venv: str) -> Path | None:
    """Execute the extracted athaniel-brain block with the env vars setup_path() sets."""
    if use_venv == "false":
        # --no-venv: athaniel-brain is NOT installed by this block (handled
        # elsewhere), so there's nothing to test here.
        return None

    command_link_dir = tmp_path / "local_bin"
    command_link_dir.mkdir()
    athaniel_bin = tmp_path / "venv" / "bin" / "python"
    athaniel_bin.parent.mkdir(parents=True)
    athaniel_bin.write_text("#!/bin/sh\n", encoding="utf-8")
    install_dir = tmp_path / "install"
    install_dir.mkdir()

    script = (
        "set -e\n"
        f"ATHANIEL_BIN={athaniel_bin}\n"
        f"INSTALL_DIR={install_dir}\n"
        f"command_link_dir={command_link_dir}\n"
        f"command_link_display_dir={command_link_dir}\n"
        f"USE_VENV={use_venv}\n"
        "log_success(){ :; }\n" + _extract_athaniel_brain_shim_block()
    )
    result = subprocess.run(
        ["bash", "-c", script],
        capture_output=True,
        text=True,
        cwd=tmp_path,
    )
    assert result.returncode == 0, (
        f"athaniel-brain shim block failed:\nstdout={result.stdout}\nstderr={result.stderr}"
    )
    return command_link_dir / "athaniel-brain"


def test_venv_install_writes_executable_athaniel_brain_launcher(tmp_path):
    """venv install must write a user-executable athaniel-brain launcher."""
    shim = _run_athaniel_brain_block(tmp_path, "true")
    assert shim is not None
    assert shim.is_file()
    assert shim.stat().st_mode & stat.S_IXUSR, "launcher must be user-executable"

    text = shim.read_text(encoding="utf-8")
    assert "unset PYTHONPATH" in text
    assert "unset PYTHONHOME" in text
    assert "run_agent.py" in text, "athaniel-brain must dispatch to run_agent.py"


def test_athaniel_brain_launcher_cleanup_on_uninstall(tmp_path):
    """uninstall.remove_wrapper_script() must remove athaniel-brain alongside
    athaniel and athaniel-acp."""
    from athaniel_cli.uninstall import remove_wrapper_script

    # Simulate a athaniel-brain wrapper in the user-local location
    local_shim = tmp_path / ".local" / "bin" / "athaniel-brain"
    local_shim.parent.mkdir(parents=True)
    local_shim.write_text("#!/usr/bin/env bash\nexec athaniel-brain\n", encoding="utf-8")

    with patch.object(Path, "home", return_value=tmp_path):
        removed = remove_wrapper_script()

    assert local_shim in removed, "local athaniel-brain wrapper must be removed"
